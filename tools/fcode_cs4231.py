#!/usr/bin/env python3
"""fcode_cs4231.py --sv > rtl/sun4m/cs4231_fcode.sv
fcode_cs4231.py --sv-slote > rtl/sun4m/slote_fcode.sv
fcode_cs4231.py --bin FILE [--slote]

The SS20's two FCode images of our own (FCODE_CS4231, FCODE_SLOTE).

FCODE_CS4231, the FCode PROM of the SS20's audio "card": the SS5's CS4231 +
APC (rtl/sun4m/cs4231.sv) put in SBus slot 3. A Sun OBP
probing the slot reads this image at the slot's base and builds the node a
Sun OBP 2.15 builds for the SS5's on-board CS4231
(docs/rom-disassembly/ss5-obp/device-tree.md):

    name         SUNW,CS4231
    device_type  serial
    reg          <slot 0x0c000000 0x40>
    interrupts   5            (SBus level 5)
    intr         <0x39 0>     (processor level 9)

The OpenBIOS in bios/ does not run slot FCode; it builds the same node itself
(bios/openbios/drivers/sbus.c, sbus_probe_slot_ss10). The image is tokenized
here, from the words below, so it is our own (GPL-2.0-or-later).

FCODE_SLOTE, at SBus slot e +0x1000: a real SS20 has its DBRI there. The Sun
OBP probes slot e with a stub of its own (docs/rom-disassembly/ss20-obp-2.25,
fcode-000299a0) that byte-loads the DBRI's FCode from +0x1000, then adds the
SpeakerBox properties; the core has no DBRI, and with nothing there (0 =
end0) the node had no name, which NeXTSTEP's sbus_config faults on (a NULL
"name"). This image only names it, "dbri-absent": no OS binds a driver to it
(theirs match SUNW,DBRIe).

FCode (IEEE 1275-1994): start1 (0xf1), format, a 16-bit checksum of the bytes
after the 8-byte header, the 32-bit length (header included), the tokens,
end0. One-byte tokens 0x10-0xff, two-byte tokens 0x01xx-0x0fxx.
"""
import sys

# The IEEE 1275 names, with the OBP 2.x names in the comments
TOK = {
    'b(lit)': 0x10, 'b(")': 0x12, '+': 0x1e,
    'my-address': 0x102, 'my-space': 0x103,
    'property': 0x110,          # attribute
    'encode-int': 0x111,        # xdrint
    'encode+': 0x112,           # xdr+
    'encode-string': 0x114,     # xdrstring
    'reg': 0x116,
    'device-type': 0x11a,
    'device-name': 0x201,       # name
    'end0': 0x00,
}

# The node: ( a Forth-like list; numbers are b(lit), "..." strings b(") )
WORDS = [
    '"SUNW,CS4231', 'device-name',
    '"serial', 'device-type',
    'my-address', 0x0c000000, '+', 'my-space', 0x40, 'reg',
    5, 'encode-int', '"interrupts', 'property',
    0x39, 'encode-int', 0, 'encode-int', 'encode+', '"intr', 'property',
    'end0',
]

WORDS_SLOTE = [
    '"dbri-absent', 'device-name',
    'end0',
]


def token(t):
    return bytes([t]) if t < 0x100 else bytes([t >> 8, t & 0xff])


def body(words):
    out = b''
    for w in words:
        if isinstance(w, int):
            out += token(TOK['b(lit)']) + w.to_bytes(4, 'big')
        elif w.startswith('"'):
            s = w[1:].encode()
            out += token(TOK['b(")']) + bytes([len(s)]) + s
        else:
            out += token(TOK[w])
    return out


def image(words):
    b = body(words)
    length = 8 + len(b)
    csum = sum(b) & 0xffff
    return bytes([0xf1, 0x08]) + csum.to_bytes(2, 'big') + length.to_bytes(4, 'big') + b


def sv():
    """cs4231_fcode: FCODE_CS4231 as the synchronous ROM rtl/sun4m/cs4231.sv
    serves at slot 3 offset 0 (same shape as tools/fcode2sv.py's tcx_fcode)."""
    img = image(WORDS)
    size = len(img)
    img += b'\x00' * (-len(img) % 4)
    w = [int.from_bytes(img[i:i + 4], 'big') for i in range(0, len(img), 4)]
    out = [f'''// SPDX-License-Identifier: GPL-2.0-or-later
//
// cs4231_fcode: the FCode PROM of the slot-3 audio (SUNW,CS4231), 2 KB of
// 32-bit big-endian words (byte n of the image in word n/4, lane n mod 4:
// byte 0 in bits 31:24). The word at addr is in q the cycle after (a
// synchronous ROM). Words past the {size}-byte image read 0.
//
// Generated by tools/fcode_cs4231.py --sv (our own FCode, tokenized there).
// Do not edit.

module cs4231_fcode (
  input  logic        clk,
  input  logic [8:0]  addr,           // word address
  output logic [31:0] q
);

  // An initialised array, not a case: Quartus kept the case in logic.
  (* romstyle = "M10K" *) logic [31:0] rom [512];
  initial begin''']
    w += [0] * (512 - len(w))
    for i, v in enumerate(w):
        out.append(f"    rom[{i}] = 32'h{v:08X};")
    out.append('''  end

  always_ff @(posedge clk) q <= rom[addr];

endmodule''')
    return '\n'.join(out)


def sv_slote():
    """slote_fcode: FCODE_SLOTE as an iobus slave for SBus slot e."""
    img = image(WORDS_SLOTE)
    size = len(img)
    img += b'\x00' * (-len(img) % 4)
    w = [int.from_bytes(img[i:i + 4], 'big') for i in range(0, len(img), 4)]
    out = [f'''// SPDX-License-Identifier: GPL-2.0-or-later
//
// slote_fcode: SBus slot e as the core has it: no DBRI, only an FCode image
// at +0x1000 that names the node a Sun OBP's slot-e stub makes there
// ("dbri-absent", DEC-4: with nothing, the node had no name and NeXTSTEP's
// sbus_config faulted on it). The {size}-byte image in 32-bit big-endian
// words from +0x1000 (byte n in word n/4, lane n mod 4); everything else
// in the slot reads 0 and ignores writes. An iobus slave (iobus_pkg);
// addr is the offset in the slot.
//
// Generated by tools/fcode_cs4231.py --sv-slote (our own FCode, tokenized
// there). Do not edit.

module slote_fcode
  import iobus_pkg::*;
(
  input  logic     clk,
  input  logic     rst,
  input  iob_req_t bus_i,
  output iob_rsp_t bus_o
);

  logic [31:0] q;
  always_comb begin
    q = 32'h0;
    if (bus_i.addr[27:5] == 23'(32'h1000 >> 5))
      case (bus_i.addr[4:2])''']
    for i, v in enumerate(w):
        out.append(f"        3'd{i}: q = 32'h{v:08X};")
    out.append('''        default: q = 32'h0;
      endcase
  end

  always_ff @(posedge clk) begin
    bus_o <= IOB_RSP_IDLE;
    if (!rst && bus_i.req && !bus_o.ack) begin
      bus_o.ack   <= 1'b1;
      bus_o.rdata <= q;
    end
  end

  logic unused_ok;
  assign unused_ok = &{1'b0, bus_i.we, bus_i.be, bus_i.wdata, bus_i.pair, bus_i.addr[1:0]};

endmodule''')
    return '\n'.join(out)


def main():
    if sys.argv[1:] == ['--sv']:
        print(sv())
        return
    if sys.argv[1:] == ['--sv-slote']:
        print(sv_slote())
        return
    if len(sys.argv) in (3, 4) and sys.argv[1] == '--bin':
        img = image(WORDS_SLOTE if sys.argv[3:] == ['--slote'] else WORDS)
        open(sys.argv[2], 'wb').write(img)
        return
    sys.exit(__doc__)


if __name__ == '__main__':
    main()

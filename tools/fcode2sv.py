#!/usr/bin/env python3
"""fcode2sv.py QEMU,tcx.bin > rtl/sun4m/tcx_fcode.sv

Turn the TCX's FCode image into tcx_fcode, the ROM the TCX serves at its
SBus slot offset 0, where a Sun OBP probes for a card's FCode.

The image is QEMU's pc-bios/QEMU,tcx.bin (1402 bytes), built from the
OpenBIOS FCode source drivers/tcx.fs (GPL-2; QEMU pc-bios/README). The
OpenBIOS we boot carries the same driver built in and never probes the
slot, so the ROM matters to the Sun OBP and to anything reading the
slot's first bytes. Past the image the ROM reads 0, as QEMU's tcx.prom.
"""
import sys

WORDS = 512                     # 2 KiB


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = sys.argv[1]
    data = open(path, 'rb').read()
    if len(data) > WORDS * 4:
        sys.exit(f'{path}: {len(data)} bytes, more than {WORDS * 4}')
    if data[0] not in (0xF0, 0xF1, 0xF2, 0xF3, 0xFD):
        sys.exit(f'{path}: not an FCode image (first byte {data[0]:02x})')
    size = len(data)
    data += b'\x00' * (-len(data) % 4)
    w = [int.from_bytes(data[i:i + 4], 'big') for i in range(0, len(data), 4)]
    out = []
    out.append(f'''// SPDX-License-Identifier: GPL-2.0-or-later
//
// tcx_fcode: the TCX's FCode PROM, 2 KB of 32-bit big-endian words (byte n
// of the image in word n/4, lane n mod 4: byte 0 in bits 31:24). The word
// at addr is in q the cycle after (a synchronous ROM, M10K on Quartus).
// Words past the image read 0.
//
// Generated by tools/fcode2sv.py from QEMU pc-bios/QEMU,tcx.bin ({size}
// bytes), built from OpenBIOS drivers/tcx.fs (GPL-2). Do not edit.

module tcx_fcode (
  input  logic        clk,
  input  logic [8:0]  addr,           // word address
  output logic [31:0] q
);

  // An initialised array, not a case: Quartus kept the case in logic.
  (* romstyle = "M10K" *) logic [31:0] rom [512];
  initial begin''')
    w += [0] * (512 - len(w))
    for i, v in enumerate(w):
        out.append(f"    rom[{i}] = 32'h{v:08X};")
    out.append('''  end

  always_ff @(posedge clk) q <= rom[addr];

endmodule''')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
